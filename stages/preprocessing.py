import pandas as pd

strict_it_spheres = ['информационные технологии', 'информационно-вычислительное обслуживание']
it_titles = [
    'разработчик', 'программист', 'devops', 'системный администратор', 'сисадмин',
    'тестировщик', 'аналитик данных', 'data scientist', 'data engineer',
    'frontend', 'backend', 'fullstack', 'верстальщик', '1с-программист',
    'it-специалист', 'it инженер', 'архитектор по', 'инженер-программист',
    'системный инженер', 'специалист по защите информации', 'инженер по тестированию',
    'техническая поддержка', 'системный техник'
]
it_tech = [
    'python', 'java ', 'javascript', 'c++', 'c#', 'react', 'angular', 'vue',
    'sql', 'postgresql', 'mysql', 'oracle', 'docker', 'kubernetes', 'git', 'linux'
]

blacklist_titles = [
    'учитель', 'преподаватель', 'доцент', 'репетитор', 'воспитатель', 'профессор',
    'бухгалтер', 'кадр', 'почтальон', 'экономист', 'юрист', 'юрисконсульт',
    'секретарь', 'делопроизводитель', 'слесарь', 'водитель', 'охранник',
    'уборщик', 'повар', 'продавец', 'медицинск', 'врач', 'медсестр',
    'менеджер по продажам', 'специалист по кадрам',
    'почт', 'клиентск', 'оператор связи', 'отделения связи'
]

sphere_col = df['professionalSphereName'].fillna('').astype(str).str.lower()
name_col = df['vacancyName'].fillna('').astype(str).str.lower()
skills_col = (df['hardSkills'].fillna('').astype(str) + ' ' + df['skills'].fillna('').astype(str)).str.lower()

cond_sphere = sphere_col.apply(lambda x: any(s in x for s in strict_it_spheres))
cond_title = name_col.apply(lambda x: any(t in x for t in it_titles))
cond_skills = skills_col.apply(lambda x: any(tech in x for tech in it_tech))
cond_blacklist = name_col.apply(lambda x: any(b in x for b in blacklist_titles))

df_final = df[(cond_sphere | cond_title | cond_skills) & ~cond_blacklist].copy()

print(f"После чистки осталось IT-вакансий: {len(df_final)}")

df_final.to_csv('it_vacancies_final.csv', index=False, encoding='utf-8-sig')

